def sanitize_lua_str(s: str) -> str:
    s = (s or "").replace("\r", " ").replace("\n", " ")
    if len(s) > MAX_TEXT_LEN:
        s = s[:MAX_TEXT_LEN]
    return s.replace("\\", "\\\\").replace('"', '\\"')


def _scan_code(line: str):
    """Split a Lua line into (code, comment) at the first `--` outside a
    string literal. comment is "" when there is none."""
    in_str = None
    esc = False
    i = 0
    while i < len(line):
        ch = line[i]
        if esc:
            esc = False
        elif in_str:
            if ch == "\\":
                esc = True
            elif ch == in_str:
                in_str = None
        else:
            if ch == '"' or ch == "'":
                in_str = ch
            elif ch == "-" and line.startswith("--", i):
                return line[:i].rstrip(), line[i + 2:].strip()
        i += 1
    return line.rstrip(), ""


def _paren_depth(code: str) -> int:
    depth = 0
    in_str = None
    esc = False
    for ch in code:
        if esc:
            esc = False
            continue
        if in_str:
            if ch == "\\":
                esc = True
            elif ch == in_str:
                in_str = None
            continue
        if ch == '"' or ch == "'":
            in_str = ch
        elif ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
    return depth


_STMT_START_RE = re.compile(r"^(?:o\.bind(?:_toggle)?|hl\.unbind)\s*\(")
_UNBIND_RE = re.compile(r'^hl\.unbind\s*\(\s*["\']([^"\']+)["\']\s*\)\s*$')
_BIND_HEADER_RE = re.compile(
    r"(o\.bind(?:_toggle)?)\s*\(\s*[\"']([^\"']+)[\"']\s*,\s*"
    r"(?:[\"']([^\"']+)[\"']|nil)\s*,\s*"
)


def iter_statements(text: str, first_line: int = 1, allow_disabled: bool = False):
    """Yield top-level o.bind / o.bind_toggle / hl.unbind statements found in
    text. Continuation lines are joined until the parentheses balance, so
    multi-line calls get their full action. Loop forms such as
    o.bind("SUPER + " .. key, ...) and hl.bind(...) are simply skipped by the
    later parse step. Yields dicts {line, code, comment, disabled}."""
    lines = text.split("\n")
    n = len(lines)
    i = 0
    while i < n:
        s = lines[i].strip()
        disabled = False
        if allow_disabled and s.startswith(DISABLED_PREFIX.strip()):
            s = s[len(DISABLED_PREFIX.strip()):].strip()
            disabled = True
        if not s or s.startswith("--") or not _STMT_START_RE.match(s):
            i += 1
            continue
        code, comment = _scan_code(s)
        j = i
        depth = _paren_depth(code)
        while depth > 0 and j + 1 < n and (j - i) < MAX_CONTINUATION_LINES:
            j += 1
            c2, cm2 = _scan_code(lines[j].strip())
            if c2:
                code = code + " " + c2
            if cm2 and not comment:
                comment = cm2
            depth = _paren_depth(code)
        if depth == 0:
            yield {"line": first_line + i, "end_line": first_line + j, "code": code.strip(),
                   "comment": comment, "disabled": disabled}
        i = j + 1


def _parse_bind_line(line: str):
    """Parse one (already joined) o.bind/o.bind_toggle call. Returns
    (raw_key, description, action_text, opts_text|None) or None."""
    m = _BIND_HEADER_RE.match(line)
    if not m:
        return None
    raw_key = m.group(2).strip()
    desc = (m.group(3) or "").strip()
    pos = m.end()
    depth_paren = 0
    depth_brace = 0
    in_string = None
    escape_next = False
    action_start = pos
    while pos < len(line):
        ch = line[pos]
        if escape_next:
            escape_next = False
            pos += 1
            continue
        if ch == '\\' and in_string:
            escape_next = True
            pos += 1
            continue
        if ch == '"' or ch == "'":
            if not in_string:
                in_string = ch
            elif in_string == ch:
                in_string = None
            pos += 1
            continue
        if in_string:
            pos += 1
            continue
        if ch == '(':
            depth_paren += 1
        elif ch == ')':
            if depth_paren > 0:
                depth_paren -= 1
            else:
                break
        elif ch == '{':
            depth_brace += 1
        elif ch == '}':
            depth_brace -= 1
        elif ch == ',' and depth_paren == 0 and depth_brace == 0:
            break
        pos += 1
    action = line[action_start:pos].strip()
    opts = None
    if pos < len(line) and line[pos] == ',':
        opts_text = line[pos + 1:].rstrip()
        if opts_text.endswith(')'):
            opts_text = opts_text[:-1].strip()
        if opts_text:
            opts = opts_text
    return raw_key, desc, action, opts


def _is_release(opts):
    return bool(opts) and bool(re.search(r"\b(?:on_)?release\s*=\s*true", opts))


def _is_mouse(raw_key, opts):
    return "mouse" in (raw_key or "").lower() or bool(opts and re.search(r"\bmouse\s*=\s*true", opts))


def parse_statement(code: str):
    """Turn a joined statement into {"kind": "unbind", "key"} or
    {"kind": "bind", ...}. None for anything we do not understand (loop
    forms, hl.bind, ...)."""
    m = _UNBIND_RE.match(code)
    if m:
        key = normalize_key_chord(m.group(1))
        if not key:
            return None
        return {"kind": "unbind", "key": key, "raw_key": m.group(1).strip()}
    parsed = _parse_bind_line(code)
    if not parsed:
        return None
    raw_key, desc, action, opts = parsed
    key = normalize_key_chord(raw_key)
    if not key:
        return None
    fn = _BIND_HEADER_RE.match(code).group(1)
    return {
        "kind": "bind",
        "fn": fn,
        "key": key,
        "raw_key": raw_key,
        "description": desc or action.strip('"\''),
        "action": action,
        "opts": opts,
        "is_mouse": _is_mouse(raw_key, opts),
        "is_release": _is_release(opts),
    }


def _make_id(desc: str) -> str:
    return re.sub(r"\s+", " ", (desc or "").strip()).lower()


def _assign_ids(entries):
    """Identity = description (case-insensitive). When one source declares the
    same description twice (stock does: "Next track", "Reveal active window on
    top", ...), later occurrences get an "@<chord>" suffix so ids stay unique."""
    ids = set()
    for e in entries:
        base = _make_id(e.get("description")) or _make_id(e.get("action"))
        cand = base
        if cand in ids:
            cand = f"{base}@{e['key']}"
            n = 2
            while cand in ids:
                cand = f"{base}@{e['key']}#{n}"
                n += 1
        e["id"] = cand
        ids.add(cand)
    return entries


def _command_from_action(action: str) -> str:
    a = (action or "").strip()
    if len(a) >= 2 and a[0] == a[-1] and a[0] in "\"'":
        return a[1:-1].replace('\\"', '"').replace("\\\\", "\\")
    return a


def _build_action(command: str, action: str = "") -> str:
    """Turn the CLI's (command, action) pair into verbatim Lua action text."""
    for cand in (action, command):
        c = (cand or "").strip().replace("\r", " ").replace("\n", " ")
        if c.startswith("{") or c.startswith("hl.") or c.startswith("function") or re.match(r"^[A-Za-z_][\w.]*\s*\(", c):
            return c[:MAX_CMD_LEN]
    raw = (command or action or "").strip()
    if (raw.startswith('"') and raw.endswith('"')) or (raw.startswith("'") and raw.endswith("'")):
        raw = raw[1:-1]
    return '"' + sanitize_lua_str(raw[:MAX_CMD_LEN]) + '"'


