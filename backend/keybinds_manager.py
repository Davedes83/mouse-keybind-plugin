USAGE = {
    "set": "Usage: set <key> <desc> <command> [action] [old_key] [--id ID] [--displace]",
    "check": "Usage: check <key> <desc> [--id ID] [--old-key K] [--cmd C] [--action A] [--displace]",
    "reset": "Usage: reset <key|desc> [default_key] [--id ID]",
    "disable": "Usage: disable <key|desc> [--id ID]",
    "enable": "Usage: enable <key|desc> [--id ID]",
}


def _parse_argv(argv):
    """Positionals in order, plus --id/--old-key/--cmd/--action values and the
    --displace flag. Positional forms stay backward compatible."""
    pos = []
    flags = {"id": None, "old_key": "", "cmd": None, "action": None, "displace": False}
    i = 0
    while i < len(argv):
        a = argv[i]
        if a == "--displace":
            flags["displace"] = True
        elif a in ("--id", "--old-key", "--cmd", "--action"):
            if i + 1 >= len(argv):
                raise ValueError(f"{a} needs a value")
            flags[a[2:].replace("-", "_")] = argv[i + 1]
            i += 1
        elif a.startswith("--id=") or a.startswith("--old-key=") or a.startswith("--cmd=") or a.startswith("--action="):
            k, v = a[2:].split("=", 1)
            flags[k.replace("-", "_")] = v
        else:
            pos.append(a)
        i += 1
    return pos, flags


def main():
    argv = sys.argv[1:]
    if not argv:
        print(json.dumps(build_complete_model(), indent=2))
        return
    cmd = argv[0]
    try:
        pos, flags = _parse_argv(argv[1:])
    except ValueError as exc:
        print(json.dumps({"success": False, "error": str(exc)}))
        sys.exit(1)
    if cmd == "list":
        print(json.dumps(build_complete_model()))
    elif cmd == "check":
        if len(pos) < 2:
            print(json.dumps({"success": False, "error": USAGE["check"]}))
            sys.exit(1)
        res = check_keybinding(pos[0], pos[1], command=flags["cmd"] or "", action=flags["action"] or "",
                               old_key=flags["old_key"], rec_id=flags["id"], displace=flags["displace"])
        print(json.dumps(res))
    elif cmd == "set":
        if len(pos) < 3:
            print(json.dumps({"success": False, "error": USAGE["set"]}))
            sys.exit(1)
        action = pos[3] if len(pos) > 3 else ""
        old_key = pos[4] if len(pos) > 4 else flags["old_key"]
        res = set_keybinding(pos[0], pos[1], pos[2], action, old_key, rec_id=flags["id"], displace=flags["displace"])
        print(json.dumps(res))
    elif cmd == "reset":
        if len(pos) < 1:
            print(json.dumps({"success": False, "error": USAGE["reset"]}))
            sys.exit(1)
        res = reset_keybinding(pos[0], pos[1] if len(pos) > 1 else "", rec_id=flags["id"])
        print(json.dumps(res))
    elif cmd == "disable":
        if len(pos) < 1:
            print(json.dumps({"success": False, "error": USAGE["disable"]}))
            sys.exit(1)
        print(json.dumps(disable_keybinding(pos[0], rec_id=flags["id"])))
    elif cmd == "enable":
        if len(pos) < 1:
            print(json.dumps({"success": False, "error": USAGE["enable"]}))
            sys.exit(1)
        print(json.dumps(enable_keybinding(pos[0], rec_id=flags["id"])))
    elif cmd == "migrate":
        print(json.dumps(migrate_trailing()))
    elif cmd == "reload":
        print(json.dumps(reload_hyprland()))
    else:
        print(json.dumps({"success": False, "error": f"Unknown command {cmd}. Commands: list, check, set, reset, disable, enable, migrate, reload"}))
        sys.exit(1)


if __name__ == "__main__":
    main()
