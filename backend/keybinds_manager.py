def _resolve_row(rows, token, rec_id=None, default_key=""):
    """Find the row an operation targets: explicit --id, else a description
    match, else the chord (managed rows and press binds preferred; disabled
    rows also match on the chord they had)."""
    if rec_id:
        return rows.get(_make_id(rec_id)) or rows.get(rec_id)
    tid = _make_id(token)
    if tid in rows:
        return rows[tid]
    nk = normalize_key_chord(token)
    if not nk:
        return None
    cands = [r for r in rows.values() if r["key"] == nk]
    if not cands:
        cands = [r for r in rows.values() if not r["key"] and nk in (r["last_key"], r["default_key"], r["stock_key"])]
    if not cands:
        return None
    ndef = normalize_key_chord(default_key) if default_key else ""
    cands.sort(key=lambda r: (not r["managed"], r["is_release"], ndef and r["default_key"] != ndef, r["id"]))
    return cands[0]


def _resolve_set_id(rows, description, old_key="", rec_id=None):
    if rec_id:
        return _make_id(rec_id) if (_make_id(rec_id) in rows or "@" not in rec_id) else rec_id
    did = _make_id(description)
    if did in rows:
        return did
    nok = normalize_key_chord(old_key) if old_key else ""
    if nok:
        cands = [r for r in rows.values() if r["key"] == nok]
        if len(cands) == 1:
            return cands[0]["id"]
    return did


def _locked_info(row):
    if row and row["source"] == "user-file" and not row["managed"]:
        return {"file_line": row["file_line"],
                "reason": "hand-written in bindings.lua; the plugin never edits it, an edit shadows it from the managed block"}
    return None


def _diff_blocks(old_block, new_block):
    skip = {BLOCK_START, BLOCK_END, BLOCK_HEADER}
    old_lines = [l for l in (old_block or "").split("\n") if l.strip() and l not in skip]
    new_lines = [l for l in (new_block or "").split("\n") if l.strip() and l not in skip]
    old_set, new_set = set(old_lines), set(new_lines)
    added = [l for l in new_lines if l not in old_set]
    would_unbind = []
    would_write = []
    for l in added:
        m = _UNBIND_RE.match(l)
        (would_unbind if m else would_write).append(m.group(1) if m else l)
    would_remove = [l for l in old_lines if l not in new_set]
    return would_unbind, would_write, would_remove


def _plan_set(ctx, records, rows, rid, norm_key, description, lua_action, displace, opts_override=None):
    existing = next((r for r in records if r["id"] == rid), None)
    base = ctx.base.get(rid)
    row = rows.get(rid)
    holders = [r for r in rows.values() if r["key"] == norm_key and r["id"] != rid]
    conflict = holders[0] if holders else None
    opts = opts_override if opts_override is not None else ((existing or row or {}).get("opts"))
    fn = (existing or row or {}).get("fn") or "o.bind"
    plan = {"conflict": _public_row(conflict) if conflict else None, "displaced": None,
            "displaced_all": [], "would_unbind": [], "would_write": [], "would_remove": [],
            "changed": False, "records": records, "block": ctx.block, "id": rid}
    if holders and not displace:
        return plan
    new_records = [dict(r) for r in records if r["id"] != rid]
    for h in holders:
        rec = next((r for r in new_records if r["id"] == h["id"]), None)
        if rec:
            rec["last_key"] = rec["key"]
            rec["key"] = None
        else:
            new_records.append({
                "id": h["id"], "description": h["description"], "key": None, "last_key": h["key"],
                "action": h["action"], "opts": h["opts"], "fn": h["fn"], "origin_key": h["key"],
            })
    # Exactly the state the identity has outside the block: no record needed
    # (and an existing one is dropped).
    identical_to_base = (
        not holders and base is not None and base["key"] == norm_key
        and base["action"] == lua_action and base["description"] == description
        and (base.get("opts") or None) == (opts or None)
    )
    if not identical_to_base:
        new_records.append({
            "id": rid, "description": description, "key": norm_key, "last_key": None,
            "action": lua_action, "opts": opts, "fn": fn, "origin_key": ctx.origin_for(rid),
        })
    new_block = render_block(new_records, ctx) if new_records else ""
    plan["records"] = new_records
    plan["block"] = new_block
    plan["changed"] = new_block != (ctx.block or "")
    plan["would_unbind"], plan["would_write"], plan["would_remove"] = _diff_blocks(ctx.block, new_block)
    if holders:
        new_rows = apply_records(ctx, new_records)
        _compute_conflicts(new_rows)
        plan["displaced_all"] = [_public_row(new_rows[h["id"]]) for h in holders]
        plan["displaced"] = plan["displaced_all"][0]
    return plan


def _validate_set_inputs(key, description, command, action):
    norm_key = normalize_key_chord(key)
    if not norm_key:
        return None, {"success": False, "error": "Invalid key combination", "key": key}
    if not (description or "").strip():
        return None, {"success": False, "error": "Description is required", "key": norm_key}
    if len(description or "") > MAX_TEXT_LEN or len(command or "") > MAX_CMD_LEN or len(action or "") > MAX_CMD_LEN:
        return None, {"success": False, "error": "Description or command exceeds allowed length", "key": norm_key}
    return norm_key, None


def check_keybinding(key, description, command="", action="", old_key="", rec_id=None, displace=False):
    """Pure: what `set` with the same arguments would do. No write."""
    norm_key, err = _validate_set_inputs(key, description, command, action)
    if err:
        return err
    ctx, records, rows = _load_all()
    rid = _resolve_set_id(rows, description, old_key, rec_id)
    row = rows.get(rid)
    if command or action:
        lua_action = _build_action(command, action)
    else:
        lua_action = row["action"] if row else '""'
    plan = _plan_set(ctx, records, rows, rid, norm_key, description.strip(), lua_action, displace)
    return {
        "key": norm_key,
        "id": rid,
        "conflict": plan["conflict"],
        "displaced": plan["displaced"],
        "displaced_all": plan["displaced_all"],
        "would_unbind": plan["would_unbind"],
        "would_write": plan["would_write"],
        "would_remove": plan["would_remove"],
        "changed": plan["changed"],
        "locked": _locked_info(row),
    }


def set_keybinding(key, description, command, action="", old_key="", rec_id=None, displace=False,
                   override_conflicts=None):
    norm_key, err = _validate_set_inputs(key, description, command, action)
    if err:
        return err
    description = description.strip()
    ctx, records, rows = _load_all()
    rid = _resolve_set_id(rows, description, old_key, rec_id)
    row = rows.get(rid)
    if command or action:
        lua_action = _build_action(command, action)
    else:
        lua_action = row["action"] if row else '""'
    plan = _plan_set(ctx, records, rows, rid, norm_key, description, lua_action, displace)
    if plan["conflict"] and not displace:
        return {
            "success": False, "key": norm_key, "id": rid, "conflict": plan["conflict"],
            "displaced": None, "reload": None,
            "error": f"{norm_key} is held by {plan['conflict']['description']}",
        }
    if not plan["changed"]:
        return {"success": True, "changed": False, "key": norm_key, "id": rid, "displaced": None,
                "reload": None, "error": None}
    res = _commit(ctx, render_file(ctx, plan["records"]), norm_key, description)
    res.update({"id": rid, "displaced": plan["displaced"], "displaced_all": plan["displaced_all"],
                "old_key": normalize_key_chord(old_key) if old_key else ""})
    return res


def _still_unbound_by(records, ctx, chord, exclude_id):
    """The record (other than exclude_id) whose rendering keeps `chord`
    unbound, or None."""
    for r in records:
        if r["id"] == exclude_id:
            continue
        if r["key"] is None and r.get("origin_key") == chord:
            return r
        if r["key"] and r.get("origin_key") == chord and r["key"] != chord:
            return r
    return None


def _refuse(row_id, chord, other_row, reason):
    return {"success": False, "key": chord, "id": row_id, "conflict": _public_row(other_row) if other_row else None,
            "reload": None, "error": reason}


def reset_keybinding(key, default_key="", rec_id=None):
    ctx, records, rows = _load_all()
    row = _resolve_row(rows, key, rec_id, default_key)
    if row is None:
        return {"success": False, "error": f"No binding matches {key}", "key": key, "reload": None}
    rec = next((r for r in records if r["id"] == row["id"]), None)
    if rec is None:
        locked = _locked_info(row)
        if locked:
            return {"success": False, "key": row["key"], "id": row["id"], "locked": locked, "reload": None,
                    "error": f"'{row['description']}' is hand-written in bindings.lua (line {locked['file_line']}); edit the file to change it"}
        return {"success": True, "changed": False, "key": row["key"], "id": row["id"], "reload": None, "error": None}
    new_records = [r for r in records if r["id"] != row["id"]]
    base = ctx.base.get(row["id"])
    if base and base["key"]:
        new_rows = apply_records(ctx, new_records)
        holders = [r for r in new_rows.values() if r["key"] == base["key"] and r["id"] != row["id"]]
        if holders:
            return _refuse(row["id"], base["key"], holders[0],
                           f"{base['key']} is held by {holders[0]['description']}")
        other = _still_unbound_by(new_records, ctx, base["key"], row["id"])
        if other:
            return _refuse(row["id"], base["key"], new_rows.get(other["id"]),
                           f"{base['key']} stays unbound: '{other['description']}' was moved off it")
    res = _commit(ctx, render_file(ctx, new_records), base["key"] if base else (row["key"] or ""), row["description"])
    res.update({"id": row["id"], "deleted": base is None})
    return res


def disable_keybinding(key, rec_id=None):
    ctx, records, rows = _load_all()
    row = _resolve_row(rows, key, rec_id)
    if row is None:
        return {"success": False, "error": f"No binding matches {key}", "key": key, "reload": None}
    if not row["key"]:
        return {"success": True, "changed": False, "key": None, "id": row["id"], "reload": None, "error": None}
    new_records = [dict(r) for r in records]
    rec = next((r for r in new_records if r["id"] == row["id"]), None)
    if rec:
        rec["last_key"] = rec["key"]
        rec["key"] = None
    else:
        new_records.append({
            "id": row["id"], "description": row["description"], "key": None, "last_key": row["key"],
            "action": row["action"], "opts": row["opts"], "fn": row["fn"], "origin_key": row["key"],
        })
    res = _commit(ctx, render_file(ctx, new_records), row["key"], row["description"])
    res.update({"id": row["id"]})
    return res


def enable_keybinding(key, rec_id=None):
    ctx, records, rows = _load_all()
    row = _resolve_row(rows, key, rec_id)
    if row is None:
        return {"success": False, "error": f"No binding matches {key}", "key": key, "reload": None}
    if row["key"]:
        return {"success": True, "changed": False, "key": row["key"], "id": row["id"], "reload": None, "error": None}
    rec = next((r for r in records if r["id"] == row["id"]), None)
    if rec is None:
        locked = _locked_info(row)
        return {"success": False, "key": None, "id": row["id"], "locked": locked, "reload": None,
                "error": f"'{row['description']}' is disabled by a hand-written hl.unbind in bindings.lua"
                         + (f" (line {locked['file_line']})" if locked else "")}
    base = ctx.base.get(row["id"])
    if base is not None:
        # Stock or hand-written identity: dropping the record restores it.
        target = base["key"]
        new_records = [r for r in records if r["id"] != row["id"]]
        if not target:
            locked = _locked_info(base)
            return {"success": False, "key": None, "id": row["id"], "locked": locked, "reload": None,
                    "error": f"'{row['description']}' has no binding to return to outside the managed block"}
    else:
        target = rec.get("last_key")
        if not target:
            return {"success": False, "key": None, "id": row["id"], "reload": None,
                    "error": f"'{row['description']}' has no remembered key to restore"}
        new_records = [dict(r) for r in records]
        for r in new_records:
            if r["id"] == row["id"]:
                r["key"] = target
                r["last_key"] = None
    new_rows = apply_records(ctx, new_records)
    holders = [r for r in new_rows.values() if r["key"] == target and r["id"] != row["id"]]
    if holders:
        return _refuse(row["id"], target, holders[0], f"{target} is held by {holders[0]['description']}")
    if base is not None:
        other = _still_unbound_by(new_records, ctx, target, row["id"])
        if other:
            return _refuse(row["id"], target, new_rows.get(other["id"]),
                           f"{target} stays unbound: '{other['description']}' was moved off it")
    res = _commit(ctx, render_file(ctx, new_records), target, row["description"])
    res.update({"id": row["id"]})
    return res


def migrate_trailing():
    """Move the trailing hl.unbind/o.bind lines the old plugin appended after
    the last hand-written statement (outside any marked block) into the
    managed block. Idempotent; touches nothing else."""
    ctx = load_context()
    without = _content_without_block(ctx)
    region, lines = _trailing_region(without)
    if not region:
        return {"success": True, "migrated": 0, "changed": False, "records": [], "reload": None, "error": None}
    region_set = set(region)
    # Rebuild the context as if those lines were not hand-written.
    user2 = dict(ctx.user)
    user2["binds"] = [b for b in ctx.user["binds"] if (b["line"] - 1) not in region_set]
    user2["unbinds"] = [u for u in ctx.user["unbinds"] if (u["line"] - 1) not in region_set]
    ctx2 = Context(ctx.stock, user2)
    stmts = [{"line": i + 1, "code": _scan_code(lines[i].strip())[0], "comment": "", "disabled": False} for i in region]
    migrated = _records_from_statements(stmts, ctx2)
    existing = load_records(ctx.block, ctx2)
    existing_ids = {r["id"] for r in existing}
    merged = existing + [r for r in migrated if r["id"] not in existing_ids]
    kept = [l for i, l in enumerate(lines) if i not in region_set]
    body = "\n".join(kept).rstrip("\n")
    if merged:
        new_content = (body + "\n\n" if body else NEW_FILE_HEADER + "\n") + render_block(merged, ctx2) + "\n"
    else:
        new_content = body + "\n" if body else ""
    res = _commit(ctx, new_content, "", "migrate")
    res.update({"migrated": len(region), "records": [r["id"] for r in migrated]})
    return res


