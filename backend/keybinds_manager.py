_ID_COMMENT_RE = re.compile(r"^id:\s*(.+?)\s*(?:;\s*was\s+.+)?$")


def _comment_id(comment):
    if not comment:
        return None
    m = _ID_COMMENT_RE.match(comment.strip())
    return m.group(1) if m else None


def _records_from_statements(stmts, ctx):
    """Records from parsed statements. A bind = an active record (or a disabled
    one when it came from a `-- disabled:` line). An unbind of a chord that
    some unmanaged bind still declares, with no managed bind of that identity,
    = an implicit disabled record for that identity."""
    records = {}
    unbind_chords = []
    for st_ in stmts:
        p = parse_statement(st_["code"])
        if not p:
            continue
        if p["kind"] == "unbind":
            unbind_chords.append(p["key"])
            continue
        rid = _comment_id(st_.get("comment")) or _make_id(p["description"])
        rec = {
            "id": rid,
            "description": p["description"],
            "key": None if st_.get("disabled") else p["key"],
            "last_key": p["key"] if st_.get("disabled") else None,
            "action": p["action"],
            "opts": p["opts"],
            "fn": p["fn"],
            "origin_key": ctx.origin_for(rid),
        }
        prev = records.get(rid)
        if prev is None or (prev["key"] is None and rec["key"] is not None):
            records[rid] = rec
    for chord in unbind_chords:
        for row in ctx.base.values():
            if row["key"] == chord and row["id"] not in records:
                records[row["id"]] = {
                    "id": row["id"], "description": row["description"], "key": None,
                    "last_key": chord, "action": row["action"], "opts": row["opts"],
                    "fn": row["fn"], "origin_key": chord,
                }
    return list(records.values())


def load_records(block_text, ctx):
    if not block_text:
        return []
    return _records_from_statements(list(iter_statements(block_text, allow_disabled=True)), ctx)


def _collect_unbinds(records, ctx):
    unbinds = []

    def add(k):
        if k and k not in unbinds:
            unbinds.append(k)

    for r in sorted(records, key=lambda r: r["id"]):
        if r["key"] is None:
            add(r.get("origin_key"))
        else:
            if r.get("origin_key") and r["origin_key"] != r["key"]:
                add(r["origin_key"])
            if ctx.unmanaged_holds(r["key"]):
                add(r["key"])
    return unbinds


def _format_bind(r, key=None):
    key = key or r["key"]
    desc = sanitize_lua_str(r["description"])
    action = (r.get("action") or '""').replace("\r", " ").replace("\n", " ")
    s = f'{r.get("fn") or "o.bind"}("{key}", "{desc}", {action}'
    if r.get("opts"):
        s += f', {r["opts"]}'
    s += ")"
    comments = []
    if _make_id(r["description"]) != r["id"]:
        comments.append(f"id: {r['id']}")
    if r.get("origin_key") and r["origin_key"] != key:
        comments.append(f"was {r['origin_key']}")
    if comments:
        s += " -- " + "; ".join(comments)
    return s


def render_block(records, ctx):
    """The whole managed block: all unbinds first (deduped), then binds, then
    disabled records as commented binds; stable order by id."""
    recs = sorted(records, key=lambda r: r["id"])
    lines = [BLOCK_START, BLOCK_HEADER]
    lines += [f'hl.unbind("{k}")' for k in _collect_unbinds(recs, ctx)]
    for r in recs:
        if r["key"]:
            lines.append(_format_bind(r))
    for r in recs:
        if not r["key"]:
            k = r.get("last_key") or r.get("origin_key")
            if k:
                lines.append(DISABLED_PREFIX + _format_bind(r, key=k))
    lines.append(BLOCK_END)
    return "\n".join(lines)


def render_file(ctx, records):
    """Replace-or-append the managed block; nothing outside it is touched.
    With no records left, the block is removed entirely."""
    content = ctx.content
    block = render_block(records, ctx) if records else None
    if ctx.block_span:
        s, e = ctx.block_span
        if block:
            return content[:s] + block + content[e:]
        before = content[:s].rstrip("\n")
        after = content[e:].lstrip("\n")
        out = before + "\n" if before else ""
        if after:
            out += ("\n" if before else "") + after
        return out
    if not block:
        return content
    if not ctx.user["exists"]:
        return NEW_FILE_HEADER + "\n" + block + "\n"
    if not content.strip():
        return block + "\n"
    return content.rstrip("\n") + "\n\n" + block + "\n"


