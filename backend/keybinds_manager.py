def parse_default_bindings():
    """Stock binds from $OMARCHY_PATH/default/hypr/bindings/*.lua."""
    bindings = []
    try:
        dirfd = _open_dir_fd(DEFAULT_BINDINGS_DIR)
    except (FileNotFoundError, ValueError):
        return bindings
    try:
        names = sorted(e.name for e in os.scandir(dirfd))
        file_count = 0
        total_read = 0
        for fname in names:
            if file_count >= MAX_DIR_FILES or total_read > MAX_TOTAL_READ:
                break
            file_count += 1
            if not fname.endswith(".lua"):
                continue
            try:
                src_fd = os.open(fname, os.O_RDONLY | os.O_NOFOLLOW, dir_fd=dirfd)
            except OSError:
                continue
            try:
                st = os.fstat(src_fd)
                if not stat.S_ISREG(st.st_mode) or st.st_size > MAX_FILE_BYTES:
                    continue
                content = _read_fd_capped(src_fd, MAX_FILE_BYTES)
            except Exception:
                continue
            finally:
                os.close(src_fd)
            total_read += len(content.encode("utf-8"))
            cat = _CATEGORY_BY_FILE.get(fname[:-4], "General")
            for st_ in iter_statements(content):
                p = parse_statement(st_["code"])
                if not p or p["kind"] != "bind":
                    continue
                bindings.append({
                    "source": "default",
                    "file": fname,
                    "line": st_["line"],
                    "key": p["key"],
                    "raw_key": p["raw_key"],
                    "description": p["description"],
                    "action": p["action"],
                    "opts": p["opts"],
                    "fn": p["fn"],
                    "category": cat,
                    "is_mouse": p["is_mouse"],
                    "is_release": p["is_release"],
                })
    finally:
        os.close(dirfd)
    return _assign_ids(bindings)


def parse_user_file(path=None):
    """Read the user file once. Returns {exists, content, mode, block (text or
    None), block_span ((start, end) or None), binds, unbinds} where binds and
    unbinds are the hand-written statements OUTSIDE the managed block."""
    path = path or USER_BINDINGS_PATH
    result = {"exists": False, "content": "", "mode": 0o644, "block": None,
              "block_span": None, "binds": [], "unbinds": []}
    try:
        src_fd, _ = safe_open_config(path, owner_check=True)
    except FileNotFoundError:
        return result
    try:
        content = _read_fd_capped(src_fd, MAX_FILE_BYTES)
        result["mode"] = stat.S_IMODE(os.fstat(src_fd).st_mode)
    finally:
        os.close(src_fd)
    result["exists"] = True
    result["content"] = content
    outside = content
    m = BLOCK_RE.search(content)
    if m:
        result["block"] = m.group(0)
        result["block_span"] = (m.start(), m.end())
        outside = content[:m.start()] + ("\n" * m.group(0).count("\n")) + content[m.end():]
    for st_ in iter_statements(outside):
        p = parse_statement(st_["code"])
        if not p:
            continue
        p["line"] = st_["line"]
        p["end_line"] = st_["end_line"]
        if p["kind"] == "unbind":
            result["unbinds"].append(p)
        else:
            result["binds"].append(p)
    return result


def parse_user_bindings():
    """Backward-compatible view of the hand-written part of the user file."""
    uf = parse_user_file()
    binds = []
    mouse = []
    for b in uf["binds"]:
        entry = {
            "source": "user",
            "key": b["key"],
            "raw_key": b["raw_key"],
            "description": b["description"],
            "action": b["action"],
            "is_mouse": b["is_mouse"],
            "is_release": b["is_release"],
            "line": b["line"],
        }
        (mouse if b["is_mouse"] else binds).append(entry)
    return {
        "raw_content": uf["content"],
        "unbinds": {u["key"] for u in uf["unbinds"]},
        "binds": binds,
        "mouse_binds": mouse,
    }


