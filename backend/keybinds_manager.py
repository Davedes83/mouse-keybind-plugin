def _new_row(**kw):
    row = {
        "id": "", "key": None, "description": "", "action": "", "command": "", "opts": None,
        "fn": "o.bind", "category": "Custom", "status": "custom", "source": "default",
        "managed": False, "default_key": "", "default_action": "", "stock_key": "",
        "origin_key": None, "last_key": None, "is_conflict": False, "conflict_with": [],
        "file_line": None, "file": None, "is_mouse": False, "is_release": False,
    }
    row.update(kw)
    row["command"] = _command_from_action(row["action"])
    return row


class Context:
    def __init__(self, stock, user):
        self.stock = stock
        self.user = user
        self.content = user["content"]
        self.mode = user["mode"]
        self.block = user["block"]
        self.block_span = user["block_span"]
        self.stock_chords = {s["key"] for s in stock if s["key"]}
        self.user_bind_chords = {b["key"] for b in user["binds"] if b["key"]}
        self.base = self._build_base_rows()

    def unmanaged_holds(self, key) -> bool:
        """True when a bind outside the block (stock or hand-written) declares
        this chord, so a managed bind on it needs a preceding hl.unbind."""
        return bool(key) and (key in self.stock_chords or key in self.user_bind_chords)

    def _build_base_rows(self):
        rows = {}
        for s in self.stock:
            rows[s["id"]] = _new_row(
                id=s["id"], key=s["key"], description=s["description"], action=s["action"],
                opts=s["opts"], fn=s["fn"], category=s["category"], status="default",
                source="default", default_key=s["key"], default_action=s["action"],
                stock_key=s["key"], origin_key=s["key"], file=s["file"],
                is_mouse=s["is_mouse"], is_release=s["is_release"],
            )
        unbound = {}
        for ub in self.user["unbinds"]:
            unbound.setdefault(ub["key"], ub["line"])
        for row in rows.values():
            if row["key"] in unbound:
                row.update(key=None, status="disabled", source="user-file",
                           file_line=unbound[row["key"]], last_key=row["stock_key"])
        user_binds = _assign_ids([dict(b) for b in self.user["binds"]])
        for hb in user_binds:
            base = rows.get(hb["id"])
            if base is not None and not base.get("_hand_written"):
                base.update(
                    key=hb["key"], description=hb["description"], action=hb["action"],
                    opts=hb["opts"], fn=hb["fn"], source="user-file", managed=False,
                    file_line=hb["line"], origin_key=hb["key"], last_key=None,
                    is_mouse=hb["is_mouse"], is_release=hb["is_release"], _hand_written=True,
                )
                base["command"] = _command_from_action(base["action"])
                base["status"] = "modified" if (
                    base["key"] != base["default_key"] or base["action"] != base["default_action"]
                ) else "default"
            else:
                rid = hb["id"]
                if rid in rows:
                    rid = f"{rid}@{hb['key']}"
                rows[rid] = _new_row(
                    id=rid, key=hb["key"], description=hb["description"], action=hb["action"],
                    opts=hb["opts"], fn=hb["fn"], category="Custom", status="custom",
                    source="user-file", origin_key=hb["key"], file_line=hb["line"],
                    is_mouse=hb["is_mouse"], is_release=hb["is_release"], _hand_written=True,
                )
        return rows

    def origin_for(self, rid):
        """Chord the identity holds outside the block (None when nothing
        outside the block binds it, e.g. custom or hand-unbound stock)."""
        base = self.base.get(rid)
        return base["key"] if base else None


