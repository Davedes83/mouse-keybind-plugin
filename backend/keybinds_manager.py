def apply_records(ctx, records):
    """Rows = base rows overridden by records (records > hand-written > stock)."""
    rows = {rid: dict(row) for rid, row in ctx.base.items()}
    for rec in records:
        base = ctx.base.get(rec["id"])
        if base:
            default_key = base["key"] or base["origin_key"] or ""
            default_action = base["action"]
        else:
            default_key = ""
            default_action = ""
        row = _new_row(
            id=rec["id"], key=rec["key"], description=rec["description"], action=rec["action"],
            opts=rec.get("opts"), fn=rec.get("fn") or "o.bind",
            category=base["category"] if base else "Custom",
            source="managed", managed=True, default_key=default_key, default_action=default_action,
            stock_key=base["stock_key"] if base else "", origin_key=rec.get("origin_key"),
            last_key=rec.get("last_key"), file=base["file"] if base else None,
            is_mouse=_is_mouse(rec["key"] or rec.get("last_key") or "", rec.get("opts")),
            is_release=_is_release(rec.get("opts")),
        )
        if rec["key"] is None:
            row["status"] = "disabled"
        elif base is None:
            row["status"] = "custom"
        elif rec["key"] != default_key or rec["action"] != default_action:
            row["status"] = "modified"
        else:
            row["status"] = "default"
        rows[rec["id"]] = row
    return rows


def _compute_conflicts(rows):
    """Chords held by more than one row with a key. Mouse and release binds
    are exempt, as is a group that is entirely one stock file's own
    composite (e.g. the ALT + TAB pair in tiling.lua)."""
    groups = {}
    for r in rows.values():
        r["is_conflict"] = False
        r["conflict_with"] = []
        if not r["key"] or r["is_mouse"] or r["is_release"]:
            continue
        groups.setdefault(r["key"], []).append(r)
    conflicts = []
    for k, group in groups.items():
        if len(group) < 2:
            continue
        sources = {x["source"] for x in group}
        files = {x.get("file") for x in group}
        if sources == {"default"} and len(files) == 1 and files != {None}:
            continue
        for r in group:
            r["is_conflict"] = True
            r["conflict_with"] = [o["description"] for o in group if o is not r]
        conflicts.append({
            "key": k,
            "bindings": [
                {"id": x["id"], "description": x["description"], "action": x["action"],
                 "status": x["status"], "source": x["source"], "key": x["key"]}
                for x in group
            ],
        })
    return conflicts


def _public_row(r):
    return {k: v for k, v in r.items() if not k.startswith("_")}


def _load_all():
    ctx = load_context()
    records = load_records(ctx.block, ctx)
    rows = apply_records(ctx, records)
    _compute_conflicts(rows)
    return ctx, records, rows


def _trailing_region(content_without_block):
    """Line indices (into content_without_block.split('\\n')) of the trailing
    single-line, comment-free hl.unbind/o.bind statements that sit after the
    last hand-written statement -- what the old plugin appended."""
    lines = content_without_block.split("\n")
    i = len(lines) - 1
    region = []
    while i >= 0:
        s = lines[i].strip()
        if not s:
            i -= 1
            continue
        if _STMT_START_RE.match(s):
            code, comment = _scan_code(s)
            if not comment and _paren_depth(code) == 0 and parse_statement(code):
                region.append(i)
                i -= 1
                continue
        break
    return sorted(region), lines


def _content_without_block(ctx):
    if ctx.block_span:
        s, e = ctx.block_span
        return ctx.content[:s] + ctx.content[e:]
    return ctx.content


def build_complete_model():
    ctx, records, rows = _load_all()
    all_active = sorted(
        (_public_row(r) for r in rows.values()),
        key=lambda x: (x["description"].lower(), x["key"] or ""),
    )
    conflicts = _compute_conflicts(rows)
    for r in all_active:
        src = rows[r["id"]]
        r["is_conflict"] = src["is_conflict"]
        r["conflict_with"] = src["conflict_with"]
    by_desc = {}
    for r in all_active:
        by_desc.setdefault(r["description"].lower(), r)
    catalog = []
    for preset in PRESET_CATALOG:
        hit = by_desc.get(preset["name"].lower()) or by_desc.get(preset["description"].lower())
        cat_item = dict(preset)
        cat_item["is_bound"] = bool(hit and hit["key"])
        cat_item["current_key"] = (hit["key"] or "") if hit else ""
        cat_item["row_id"] = hit["id"] if hit else None
        catalog.append(cat_item)
    catalog.sort(key=lambda x: x.get("name", "").lower())
    region, _ = _trailing_region(_content_without_block(ctx))
    return {
        "active": all_active,
        "catalog": catalog,
        "conflicts": conflicts,
        "total_active": len([b for b in all_active if b["key"]]),
        "total_modified": len([b for b in all_active if b["status"] in ("modified", "custom")]),
        "total_conflicts": len(conflicts),
        "block_exists": ctx.block is not None,
        "pending_migration": len(region),
        "mouse_settings": get_mouse_scroll_settings(),
        "user_bindings_file": USER_BINDINGS_PATH,
    }


